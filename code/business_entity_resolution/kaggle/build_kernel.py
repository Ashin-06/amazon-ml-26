"""Build a self-contained Kaggle script kernel: embeds src/fast_er/*.py, writes them on the
Kaggle box, then runs the requested stages.

Usage: python build_kernel.py OUT_DIR OWNER SLUG STAGES [--s1 "stage1 args"] [--s3 "stage3 args"] [--reuse OWNER/KERNEL]
STAGES: comma list of block_train, block_test, model, model_eval (train + holdout metrics only).
--reuse attaches an earlier kernel's output; its work/ dir (norm + candidates) is copied and reused.
"""
import argparse
import json
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("out"); ap.add_argument("owner"); ap.add_argument("slug"); ap.add_argument("stages")
ap.add_argument("--s1", default=""); ap.add_argument("--s3", default=""); ap.add_argument("--reuse")
ap.add_argument("--no-internet", action="store_true")
ap.add_argument("--gpu", action="store_true", help="request a Kaggle GPU (T4); the code auto-detects it and falls back to CPU")
a = ap.parse_args()
src = Path(__file__).resolve().parent.parent / "src" / "fast_er"
out = Path(a.out)
files = {p.name: p.read_text(encoding="utf-8") for p in sorted(src.glob("*.py"))}
body = f'''# Auto-generated by build_kernel.py — Amazon ML Challenge 2026 entity resolution pipeline.
import glob, json, os, shlex, subprocess, sys, time
FILES = {json.dumps(files)}
STAGES = {a.stages!r}.split(",")
S1_ARGS, S3_ARGS = shlex.split({a.s1!r}), shlex.split({a.s3!r})
os.makedirs("/kaggle/working/fast_er", exist_ok=True)
os.environ["FASTER_TMP"] = "/tmp"  # spill + feature caches off the 20 GB /kaggle/working quota
for n, c in FILES.items():
    open(f"/kaggle/working/fast_er/{{n}}", "w").write(c)
open("/kaggle/working/fast_er/__init__.py", "w").write("")
whl = glob.glob("/kaggle/input/**/anyascii-*.whl", recursive=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", *whl], check=False)
for mod, pkg in (("duckdb", "duckdb"), ("rapidfuzz", "rapidfuzz"), ("lightgbm", "lightgbm")):
    try: __import__(mod)
    except ImportError: subprocess.run([sys.executable, "-m", "pip", "install", "-q", pkg], check=False)
import importlib
for mod in ("duckdb", "rapidfuzz", "lightgbm", "xgboost", "anyascii", "pyarrow", "pandas", "numpy"):
    try: importlib.import_module(mod)
    except ImportError as e: raise SystemExit(f"PREFLIGHT FAILED: {{mod}} not importable ({{e}}); enable internet or attach its wheel")
PQ = os.path.dirname(glob.glob("/kaggle/input/**/train_source1.parquet", recursive=True)[0])
W = "/kaggle/working/work"
prev = glob.glob("/kaggle/input/**/work/train/cands.parquet", recursive=True)
if prev and not os.path.exists(W):  # reuse an earlier kernel's stage-1 output (not its model)
    subprocess.run(["cp", "-r", os.path.dirname(os.path.dirname(prev[0])), W], check=True)
    subprocess.run(["rm", "-rf", W + "/model"], check=True)
print("PQ", PQ, "stages", STAGES, "cpus", os.cpu_count(), "reuse", bool(prev), flush=True)
import importlib.metadata as _md
print("versions", {{p: _md.version(p) for p in ("duckdb", "lightgbm", "xgboost", "rapidfuzz", "numpy", "pandas", "pyarrow", "anyascii")}}, flush=True)
t0 = time.time()
def run(*args):
    print(">>>", *args, flush=True)
    subprocess.run([sys.executable, *args], check=True)
GT = f"{{PQ}}/train_ground_truth.parquet"
if "block_train" in STAGES:
    run("/kaggle/working/fast_er/run_stage1.py", "train", PQ, W, GT, "--mem", "18GB", *S1_ARGS)
if "block_test" in STAGES:
    run("/kaggle/working/fast_er/run_stage1.py", "test", PQ, W, "--mem", "18GB", *S1_ARGS)
if "model" in STAGES:
    run("/kaggle/working/fast_er/run_stage3.py", W, GT, "test", "/kaggle/working/out", "--mem", "8GB", "--chunks", "24", *S3_ARGS)
if "model_eval" in STAGES:
    run("/kaggle/working/fast_er/run_stage3.py", W, GT, "test", "/kaggle/working/out", "--mem", "8GB", "--chunks", "24", "--skip-predict", *S3_ARGS)
for f in glob.glob(W + "/model/metrics.json") + glob.glob(W + "/train/blocking_recall.json"):
    print(f, open(f).read()[:3000], flush=True)
if prev:  # keep the output small: reused inputs need not be re-published
    subprocess.run(["rm", "-rf", W + "/train", W + "/test"], check=False)
print(f"ALL DONE {{time.time() - t0:.0f}}s", flush=True)
'''
out.mkdir(parents=True, exist_ok=True)
(out / "script.py").write_text(body, encoding="utf-8")
meta = {"id": f"{a.owner}/{a.slug}", "title": a.slug.replace("-", " "), "code_file": "script.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": a.gpu, "enable_tpu": False,
        "enable_internet": not a.no_internet, "dataset_sources": [f"{a.owner}/amlc26-data"], "competition_sources": [],
        "kernel_sources": [a.reuse] if a.reuse else []}
(out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
print("built", out / "script.py", len(body), "bytes")
